#!/bin/bash
# Builds without Gradle.
#   SDK=... ./build.sh                 -> mingui.apk       Mingui, no root (GitHub releases; signed with
#                                         signing/app-release.jks, the same app signing key Play uses)
#   SDK=... TOOLS=... ./build.sh play aab -> mingui.aab    Google Play bundle, signed with the upload key
#   SDK=... ./build.sh root            -> mingui-root.apk  Mingui Root (GitHub releases; signed with
#                                         signing/root-release.jks when present, else the debug key)
# TOOLS must contain bundletool.jar and aapt2/aapt2 from Google Maven (the build-tools aapt2 can't make bundles).
set -euo pipefail
cd "$(dirname "$0")"
VARIANT=${1:-play}
[ "$VARIANT" = lite ] && VARIANT=play # old name
FORMAT=${2:-apk}
API=36
BT=$SDK/build-tools/36.0.0
JAR=$SDK/platforms/android-$API/android.jar
source version.properties
OUT=build/$VARIANT
PKG=io.github.abysstudio.mingui
PKG_DIR=io.github.abysstudio.mingui
rm -rf $OUT && mkdir -p $OUT/gen/$PKG_DIR $OUT/classes $OUT/dex

if [ "$VARIANT" = play ]; then
    ROOT=false
    NAME=mingui
    STRIP=ROOT_ONLY
    LINK_EXTRA=()
    OVERLAY_DIR=
    # The Play build gets a no-op RootOps: no su/pm code at all.
    SOURCES=$(find src -name '*.java' ! -name RootOps.java; find variants/play/src -name '*.java')
elif [ "$VARIANT" = root ]; then
    ROOT=true
    NAME=mingui-root
    STRIP=LITE_ONLY
    # Separate package so it installs next to the Play build; own name and icon colour.
    LINK_EXTRA=(--rename-manifest-package $PKG.root)
    OVERLAY_DIR=variants/root/res
    SOURCES=$(find src -name '*.java')
else
    echo "Unknown variant '$VARIANT' (use play or root)" >&2
    exit 1
fi
# Manifest for this variant: drop the other variant's blocks.
sed "/<!-- $STRIP -->/,/<!-- \/$STRIP -->/d" AndroidManifest.xml > $OUT/AndroidManifest.xml

cat > $OUT/gen/$PKG_DIR/BuildFlags.java <<JAVA
package $PKG;

/** Generated by build.sh. */
final class BuildFlags {
    /** true: hide blocked apps via root. false: no root, cover blocked apps with the checklist instead. */
    static final boolean ROOT = $ROOT;

    private BuildFlags() {}
}
JAVA

AAPT2=$BT/aapt2
[ "$FORMAT" = aab ] && AAPT2=$TOOLS/aapt2/aapt2
$AAPT2 compile --dir res -o $OUT/res.zip
OVERLAY=()
if [ -n "$OVERLAY_DIR" ]; then
    $AAPT2 compile --dir $OVERLAY_DIR -o $OUT/overlay.zip
    OVERLAY=(-R $OUT/overlay.zip)
fi
PROTO=()
[ "$FORMAT" = aab ] && PROTO=(--proto-format)
$AAPT2 link -I $JAR --manifest $OUT/AndroidManifest.xml --java $OUT/gen \
    --min-sdk-version 26 --target-sdk-version $API \
    --version-code $VERSION_CODE --version-name $VERSION_NAME \
    "${LINK_EXTRA[@]}" "${PROTO[@]}" -o $OUT/linked.apk $OUT/res.zip "${OVERLAY[@]}" --auto-add-overlay

# Fail the build on compile errors (warnings are filtered out of the log, not ignored errors).
rm -rf $OUT/classes
if ! javac -nowarn -source 11 -target 11 -classpath $JAR -d $OUT/classes \
    $SOURCES $(find $OUT/gen -name '*.java') > $OUT/javac.log 2>&1; then
    grep -v 'warning' $OUT/javac.log >&2
    echo "javac failed" >&2
    exit 1
fi
grep -v 'warning' $OUT/javac.log || true
$BT/d8 --release --lib $JAR --min-api 26 --output $OUT/dex $(find $OUT/classes -name '*.class')

if [ "$FORMAT" = aab ]; then
    # Bundle module layout: manifest/, dex/, res/, resources.pb
    M=$OUT/module && mkdir -p $M/manifest $M/dex
    (cd $M && unzip -q ../linked.apk)
    mv $M/AndroidManifest.xml $M/manifest/
    cp $OUT/dex/classes*.dex $M/dex/
    (cd $M && zip -qr ../base.zip .)
    rm -f $NAME.aab
    java -jar $TOOLS/bundletool.jar build-bundle --modules=$OUT/base.zip --output=$NAME.aab
    # Bundles are signed with jarsigner (apksigner can't sign them), using the Play upload key.
    source signing/upload.properties
    jarsigner -keystore signing/upload.jks -storepass "$STORE_PASS" -keypass "$KEY_PASS" \
        -sigalg SHA256withRSA -digestalg SHA-256 $NAME.aab upload >/dev/null
    echo "Built $(pwd)/$NAME.aab (v$VERSION_NAME, code $VERSION_CODE)"
    exit 0
fi

cp $OUT/linked.apk $OUT/unsigned.apk
(cd $OUT/dex && zip -q ../unsigned.apk classes*.dex)
$BT/zipalign -f 4 $OUT/unsigned.apk $OUT/aligned.apk
[ -f debug.keystore ] || keytool -genkeypair -keystore debug.keystore -storepass android \
    -keypass android -alias key -keyalg RSA -keysize 2048 -validity 10000 -dname CN=Mingui >/dev/null 2>&1
if [ "$VARIANT" = root ] && [ -f signing/root-release.properties ]; then
    # Mingui Root releases: the permanent release key (every update must use it).
    # Early builds were signed with debug.keystore, so the release key carries a rotation
    # lineage from it (signing/root-lineage): those installs update in place on Android 9+.
    # Keep debug.keystore and the lineage file backed up with the release key.
    source signing/root-release.properties
    $BT/apksigner sign --ks debug.keystore --ks-pass pass:android \
        --next-signer --ks signing/root-release.jks --ks-key-alias "$ROOT_KEY_ALIAS" \
        --ks-pass "pass:$ROOT_STORE_PASS" --key-pass "pass:$ROOT_STORE_PASS" \
        --lineage signing/root-lineage --rotation-min-sdk-version 28 --out $NAME.apk $OUT/aligned.apk
elif [ "$VARIANT" = play ] && [ -f signing/app-release.properties ]; then
    # Mingui (no root) on GitHub: signed with the app signing key that is also registered with
    # Play App Signing, so GitHub and Play installs update each other. No rotation lineage:
    # Android 8.x ignores v3 lineage and would still see the old key.
    source signing/app-release.properties
    $BT/apksigner sign --ks signing/app-release.jks --ks-key-alias "$APP_KEY_ALIAS" \
        --ks-pass "pass:$APP_STORE_PASS" --key-pass "pass:$APP_STORE_PASS" --out $NAME.apk $OUT/aligned.apk
else
    $BT/apksigner sign --ks debug.keystore --ks-pass pass:android --out $NAME.apk $OUT/aligned.apk
fi
echo "Built $(pwd)/$NAME.apk (v$VERSION_NAME, code $VERSION_CODE)"
